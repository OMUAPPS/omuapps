#include "obs-events.hpp"

#include <nlohmann/json.hpp>

ObsEvents::ObsEvents(OmuClient &client) : client(client)
{
	client.registerSignal(SIGNAL);
	obs_frontend_add_event_callback(&ObsEvents::handle, this);
}

ObsEvents::~ObsEvents()
{
	obs_frontend_remove_event_callback(&ObsEvents::handle, this);
}

void ObsEvents::handle(obs_frontend_event event, void *param)
{
	const char *eventName = name(event);
	if (!eventName)
		return;
	auto *events = static_cast<ObsEvents *>(param);
	events->client.notify(SIGNAL, ByteStrings::from(nlohmann::json(eventName).dump()));
}

